import fs from "node:fs";
import path from "node:path";
import type { ConfigBundle, Machine, OperatingSystem } from "./schema.js";
import { ensureStateDirectories } from "./state.js";

function activePackages(config: ConfigBundle, machine: Machine, profiles?: string[]) {
  const activeProfiles = new Set(profiles?.length ? profiles : machine.profiles);
  const platform =
    machine.selectors.os === "macos"
      ? "macos"
      : machine.selectors.os === "windows"
        ? "windows"
        : "ubuntu";
  return config.packages.packages.flatMap((item) => {
    if (!item.profiles.some((profile) => activeProfiles.has(profile))) return [];
    const provider = item.providers[platform];
    return provider ? [{ logicalId: item.id, provider }] : [];
  });
}

export function renderBrewfile(
  config: ConfigBundle,
  machine: Machine,
  profiles?: string[],
): string {
  const lines = ["# Generated by dev-env. Do not edit directly.", ""];
  const seen = new Set<string>();
  for (const { provider } of activePackages(config, machine, profiles)) {
    const key = `${provider.manager}:${provider.id}`;
    if (seen.has(key)) continue;
    seen.add(key);
    if (provider.manager === "brew") lines.push(`brew ${JSON.stringify(provider.id)}`);
    if (provider.manager === "brew-cask") lines.push(`cask ${JSON.stringify(provider.id)}`);
  }
  return `${lines.join("\n")}\n`;
}

export function renderWinget(config: ConfigBundle, machine: Machine, profiles?: string[]): string {
  const packageIds = activePackages(config, machine, profiles)
    .filter(({ provider }) => provider.manager === "winget")
    .map(({ provider }) => provider.id);
  const packages = [...new Set(packageIds)].map((PackageIdentifier) => ({ PackageIdentifier }));
  return `${JSON.stringify(
    {
      $schema: "https://aka.ms/winget-packages.schema.2.0.json",
      Sources: [
        {
          Packages: packages,
          SourceDetails: {
            Argument: "https://cdn.winget.microsoft.com/cache",
            Identifier: "Microsoft.Winget.Source_8wekyb3d8bbwe",
            Name: "winget",
            Type: "Microsoft.PreIndexed.Package",
          },
        },
      ],
    },
    null,
    2,
  )}\n`;
}

export function renderAptPackages(
  config: ConfigBundle,
  machine: Machine,
  profiles?: string[],
): string {
  const packages = activePackages(config, machine, profiles)
    .filter(({ provider }) => provider.manager === "apt")
    .map(({ provider }) => provider.id);
  return `${[...new Set(packages)].join("\n")}\n`;
}

export function generateNativeManifest(
  config: ConfigBundle,
  machine: Machine,
  profiles?: string[],
  osOverride?: OperatingSystem,
): string {
  const platform = osOverride ?? machine.selectors.os;
  const directory = path.join(ensureStateDirectories(), "generated", machine.id);
  fs.mkdirSync(directory, { recursive: true });
  if (platform === "macos") {
    const file = path.join(directory, "Brewfile");
    fs.writeFileSync(file, renderBrewfile(config, machine, profiles));
    return file;
  }
  if (platform === "windows") {
    const file = path.join(directory, "winget.json");
    fs.writeFileSync(file, renderWinget(config, machine, profiles));
    return file;
  }
  const file = path.join(directory, "apt-packages.txt");
  fs.writeFileSync(file, renderAptPackages(config, machine, profiles));
  return file;
}
